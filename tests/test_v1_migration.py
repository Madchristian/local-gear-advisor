def test_parse_generated_v1_converts_only_literal_generator_shape() -> None:
    record = parse_generated_v1(_v1())

    assert record.identity.name == "Synthetic"
    assert record.identity.realm == "test_realm"
    assert record.identity.spec_id == 66
    assert record.baseline_gear["shoulder"] is None
    assert record.items[0].item_id == 200101


def test_parse_generated_v1_accepts_literal_negative_delta() -> None:
    record = parse_generated_v1(_v1().replace("deltaPercent = 2", "deltaPercent = -1.5"))

    assert record.items[0].delta_percent == -1.5


@pytest.mark.parametrize(
    "tampered",
    [
        _v1().replace("schemaVersion = 1", "schemaVersion = os.execute('bad')"),
        _v1().replace("schemaVersion = 1", "schemaVersion = true"),
        _v1().replace(
            "  generatedAt = 1785573600,\n",
            "  generatedAt = 1785573600,\n  extra = 1,\n",
        ),
        _v1().replace(
            "  generatedAt = 1785573600,\n",
            "  generatedAt = 1785573600,\n  generatedAt = 1785573600,\n",
        ),
        _v1().replace('status = "simulated"', 'status = "unknown"'),
    ],
)
def test_parse_generated_v1_rejects_code_extras_duplicates_and_wrong_status(tampered: str) -> None:
    with pytest.raises(MigrationError):
        parse_generated_v1(tampered)

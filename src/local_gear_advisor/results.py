_BASELINE_SLOTS = (
    "head",
    "neck",
    "shoulder",
    "back",
    "chest",
    "wrist",
    "hands",
    "waist",
    "legs",
    "feet",
    "finger1",
    "finger2",
    "trinket1",
    "trinket2",
    "main_hand",
    "off_hand",
)


@dataclass(frozen=True)
class EvaluatedItem:
    item_id: int
    item_name: str | None
    options: str
    fingerprint: str
    best_slot: str
    baseline_dps: float
    candidate_dps: float
    delta_percent: float
    iterations: int


@dataclass(frozen=True)
class Evaluation:
    generated_at: int
    simc_version: str
    git_revision: str
    fight_style: str
    game_version: str
    dbc_source: str
    baseline_dps: float
    items: tuple[EvaluatedItem, ...]


def evaluate_results(
    profile: SimcExport,
    built: BuiltProfileSets,
    report: ParsedSimcReport,
    *,
    generated_at: int,
) -> Evaluation:
    if generated_at < 0:
        raise ValueError("generated_at must not be negative")
    grouped: dict[str, list[tuple[ProfileVariant, float]]] = {}
    for variant in built.variants:
        try:
            value = report.variant_dps[variant.profileset_name]
        except KeyError as exc:
            raise SimcRunError(f"missing result for {variant.profileset_name}") from exc
        grouped.setdefault(variant.item_fingerprint, []).append((variant, value))

    by_fingerprint = {candidate.fingerprint: candidate for candidate in profile.candidates}
    items: list[EvaluatedItem] = []
    seen: set[str] = set()
    for candidate in profile.candidates:
        if candidate.fingerprint in seen:
            continue
        seen.add(candidate.fingerprint)
        choices = grouped.get(candidate.fingerprint)
        if not choices:
            raise SimcRunError(f"candidate {candidate.item_id} has no simulated variants")
        best_variant, best_dps = max(choices, key=lambda choice: choice[1])
        iterations = report.iterations[best_variant.profileset_name]
        delta_percent = ((best_dps / report.baseline_dps) - 1.0) * 100.0
        source = by_fingerprint[candidate.fingerprint]
        items.append(
            EvaluatedItem(
                item_id=source.item_id,
                item_name=source.name,
                options=source.options,
                fingerprint=source.fingerprint,
                best_slot=best_variant.target_slot,
                baseline_dps=report.baseline_dps,
                candidate_dps=best_dps,
                delta_percent=delta_percent,
                iterations=iterations,
            )
        )
    return Evaluation(
        generated_at=generated_at,
        simc_version=report.simc_version,
        git_revision=report.git_revision,
        fight_style=report.fight_style,
        game_version=report.game_version,
        dbc_source=report.dbc_source,
        baseline_dps=report.baseline_dps,
        items=tuple(items),
    )


def _lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _number(value: float) -> str:
    return format(value, ".12g")


def ensure_supported_profile(profile: SimcExport) -> int:
    registry = load_spec_registry()
    try:
        return registry.specs[(profile.character_class, profile.spec)]
    except KeyError as exc:
        raise ValueError(
            f"unsupported class/spec pair: {profile.character_class}/{profile.spec}"
        ) from exc


def render_results_lua(profile: SimcExport, built: BuiltProfileSets, result: Evaluation) -> str:
    spec_id = ensure_supported_profile(profile)
    lines = [
        "-- Generated by Local Gear Advisor. Do not edit while WoW is running.",
        "LocalGearAdvisorResults = {",
        "  schemaVersion = 1,",
        f"  generatedAt = {result.generated_at},",
        f"  profileHash = {_lua_string(built.profile_hash)},",
        f"  simcVersion = {_lua_string(result.simc_version)},",
        f"  simcRevision = {_lua_string(result.git_revision)},",
        f"  gameVersion = {_lua_string(result.game_version)},",
        f"  dbcSource = {_lua_string(result.dbc_source)},",
        f"  characterName = {_lua_string(profile.character_name)},",
        f"  region = {_lua_string(profile.region)},",
        f"  server = {_lua_string(profile.server)},",
        f"  class = {_lua_string(profile.character_class)},",
        f"  spec = {_lua_string(profile.spec)},",
        f"  specID = {spec_id},",
        f"  level = {profile.level},",
        f"  race = {_lua_string(profile.race)},",
        f"  talents = {_lua_string(profile.talents)},",
        "  traitSystems = {",
    ]
    for key, value in sorted(profile.trait_systems.items()):
        lines.append(f"    {key} = {_lua_string(value)},")
    lines.extend(
        [
            "  },",
            "  baselineGear = {",
        ]
    )
    for slot in _BASELINE_SLOTS:
        item = profile.equipped.get(slot)
        value = _lua_string(item.options) if item is not None else "false"
        lines.append(f"    {slot} = {value},")
    lines.extend(
        [
            "  },",
            f"  fightStyle = {_lua_string(result.fight_style)},",
            f"  baselineDps = {_number(result.baseline_dps)},",
            "  items = {",
        ]
    )
    for item in result.items:
        lines.extend(
            [
                f"    [{_lua_string(item.options)}] = {{",
                f"      itemID = {item.item_id},",
                f"      name = {_lua_string(item.item_name or '')},",
                f"      fingerprint = {_lua_string(item.fingerprint)},",
                f"      bestSlot = {_lua_string(item.best_slot)},",
                f"      candidateDps = {_number(item.candidate_dps)},",
                f"      deltaPercent = {_number(item.delta_percent)},",
                f"      iterations = {item.iterations},",
                '      status = "simulated",',
                "    },",
            ]
        )
    lines.extend(["  },", "}", ""])
    return "\n".join(lines)


def write_atomic_verified(target: Path, content: str) -> None:
    target = target.resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    lock = target.with_name(f"{target.name}.lock")
    try:
        lock_fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError as exc:
        raise OSError(f"publication is already in progress: {lock}") from exc
    try:
        os.write(lock_fd, f"pid={os.getpid()}\n".encode("ascii"))
        os.fsync(lock_fd)
        data = content.encode("utf-8")
        expected = hashlib.sha256(data).digest()
        old_data = target.read_bytes() if target.exists() else None
        temp = target.with_name(f"{target.name}.tmp-{uuid.uuid4().hex}")
        try:
            with temp.open("xb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            if hashlib.sha256(temp.read_bytes()).digest() != expected:
                raise OSError("temporary result verification failed")
            os.replace(temp, target)
            if hashlib.sha256(target.read_bytes()).digest() != expected:
                raise OSError("published result verification failed")
        except Exception:
            if temp.exists():
                temp.unlink()
            current_data = target.read_bytes() if target.exists() else None
            if old_data is not None and current_data != old_data:
                rollback = target.with_name(f"{target.name}.rollback-{uuid.uuid4().hex}")
                rollback.write_bytes(old_data)
                os.replace(rollback, target)
            elif old_data is None and target.exists():
                target.unlink()
            raise
    finally:
        os.close(lock_fd)
        try:
            lock.unlink()
        except FileNotFoundError:
            pass
